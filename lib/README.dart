/// README (инструкции по запуску)
///
/// 1) Установи Flutter stable:
///    flutter --version
///
/// 2) Создай проект и замени lib/ на файлы из ответа:
///    flutter create messenger_ui
///    (скопируй файлы в папку проекта, соблюдая пути)
///
/// 3) Поставь зависимости:
///    flutter pub get
///
/// 4) Запусти:
///    flutter run
///
/// Данные:
/// - при первом запуске приложение заполнится моками (users/chats/messages),
/// - дальше все изменения (чаты/сообщения/черновики/тема) сохраняются локально в Hive.
///
/// Ограничения прототипа (осознанно):
/// - нет сервера и синхронизации,
/// - статус online/last seen — мок,
/// - unreadCount — мок (для UI).